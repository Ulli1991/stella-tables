#!/usr/bin/env python3
"""make_chem_tables.py -- machine-extract the DATA arrays of the SGCHEM table layer from the Fortran sources in
chem_tables_source/ (S. Glover's SGChem).  Writes sgchem_chem_tables.bin; with --header also the legacy
chem_tables_data.h (the former GIZMO tables_extract.py output, byte-identical).
usage: make_chem_tables.py out.bin [--header chem_tables_data.h] [--loader DIR] [--src DIR]
Binary format: "SGCT0001", uint64 N, then N x { char name[48] (NUL padded), uint64 n, float64[n] }, all little-endian.
Names are the old C identifiers (dat_h2_lte, ...).

Arrays extracted (no hand retyping, per Gate-2 rules):
  mol_data.h : h2_lte, h2_h_rate, h2_h2_rate            (41 each, NH2DATA)
               co_temp(12), co_column(10), co_data_L0(12),
               co_data_LTE(120), co_data_n05(120), co_data_alp(120)
               co_vib_temp(6), co_vib_column(8), co_vib_LTE(48)
  coolinmo.F : coolatom(81), ca2(76)          (DATA statements)
               HeI_tbl(51), HeII_tbl(51)      (array-constructor assignments)
  h2heat.h   : h2_rv_heat(1914)               (compute_h2_heating_fraction, net 15)
  shield_data_visser.h : vis_co_columns(47), vis_h2_columns(42), vis_co_factors(1974)
"""
import re, sys, os, struct, argparse

HERE = os.path.dirname(os.path.abspath(__file__))
CANON = os.path.join(HERE, "chem_tables_source")
ARRAYS = []

def strip_source(path):
    """Return logical source lines (continuations joined, comments dropped)."""
    lines = []
    for raw in open(path):
        raw = raw.rstrip("\n")
        if not raw.strip():
            continue
        # fixed-form comment
        if raw[0:1] in ("c", "C", "*", "!"):
            continue
        if raw.lstrip().startswith("#"):   # cpp
            continue
        lines.append(raw)
    # join continuations: col-6 non-blank (we accept any of $ & * digits)
    logical = []
    for ln in lines:
        if len(ln) > 5 and ln[5] not in (" ",) and ln[:5].strip() == "":
            if logical:
                logical[-1] += " " + ln[6:]
                continue
        logical.append(ln)
    return logical

FNUM = re.compile(r"[-+]?(?:\d+\.?\d*|\.\d+)(?:[dDeE][-+]?\d+)?")

def parse_numlist(txt):
    """Parse a Fortran numeric list with the compiler's OWN literal kinds.

    CRITICAL (found 2026-07-29 while golden-testing the cl1-3/cl6 splines):
    these DATA statements are written as bare decimals -- `-25.390`, not
    `-25.390d0`.  In Fortran a literal without a `D` exponent is a DEFAULT REAL
    (single precision) constant; it is rounded to float32 and only then
    promoted to the real*8 array.  The build carries no -fdefault-real-8
    (tests/onezone/Makefile FFLAGS: -O2 -cpp -ffixed-line-length-none
    -fno-second-underscore), so what the running code actually holds is
    float32(-25.390) = -25.389999389648438, which is ~6e-7 away in log10 and
    ~1.4e-6 in the 10**x rate.  Reading these as exact doubles is therefore
    NOT a faithful port -- it silently "improves" the table by ~2e-6 relative.
    We reproduce the compiler: D/d exponent -> double, everything else -> f32.
    """
    vals = []
    for m in FNUM.finditer(txt):
        tok = m.group(0)
        s = tok.replace("d", "e").replace("D", "e")
        v = float(s)
        if "d" not in tok and "D" not in tok:
            v = struct.unpack("f", struct.pack("f", v))[0]   # default REAL kind
        vals.append(v)
    return vals

def extract_data(logical, name):
    """DATA name /..../"""
    pat = re.compile(r"^\s*DATA\s+" + re.escape(name) + r"\s*/(.*)/\s*$",
                     re.IGNORECASE)
    for ln in logical:
        m = pat.match(ln)
        if m:
            return parse_numlist(m.group(1))
    raise KeyError("DATA %s not found" % name)

def extract_ctor(logical, name):
    """name = (/ ... /)"""
    pat = re.compile(r"^\s*" + re.escape(name) + r"\s*=\s*\(/(.*)/\)\s*$")
    for ln in logical:
        m = pat.match(ln)
        if m:
            return parse_numlist(m.group(1))
    raise KeyError("ctor %s not found" % name)

def emit(f, cname, vals, expect):
    if len(vals) != expect:
        raise SystemExit("FATAL: %s has %d values, expected %d"
                         % (cname, len(vals), expect))
    ARRAYS.append((cname, vals))

def write_header(path):
    with open(path, "w") as f:
        f.write("// AUTO-GENERATED by tables_extract.py -- DO NOT EDIT.\n")
        f.write("// DATA arrays machine-extracted from canonical Fortran"
                " (mol_data.h, coolinmo.F, isrf.h, shield_data.h,"
                " highn_gamma.h, h2heat.h).\n#ifndef CHEM_TABLES_DATA_H\n"
                "#define CHEM_TABLES_DATA_H\n\n")
        for cname, vals in ARRAYS:
            f.write("static const double %s[%d] = {\n" % (cname, len(vals)))
            for i in range(0, len(vals), 5):
                f.write("    " + ", ".join("%.17g" % v for v in vals[i:i+5]) + ",\n")
            f.write("};\n\n")
        f.write("#endif /* CHEM_TABLES_DATA_H */\n")

def write_loader(d):
    """Proposal for GIZMO: extern declarations + one definition/loader TU, replacing the generated data header."""
    with open(os.path.join(d, "chem_tables_data.h"), "w") as f:
        f.write("// generated by stella-tables chemistry/sgchem/make_chem_tables.py --loader; arrays are read from sgchem_chem_tables.bin\n"
                "#ifndef CHEM_TABLES_DATA_H\n#define CHEM_TABLES_DATA_H\n")
        for c, v in ARRAYS:
            f.write("extern double %s[%d];\n" % (c, len(v)))
        f.write("// 0 = loaded; 1 = file missing or its arrays differ in name, size or order from this header\n"
                "int chem_tables_data_load(const char* dir);\n#endif\n")
    with open(os.path.join(d, "chem_tables_data.cc"), "w") as f:
        f.write('// generated by stella-tables chemistry/sgchem/make_chem_tables.py --loader\n#include "chem_tables_data.h"\n'
                '#include <cstdio>\n#include <cstdint>\n#include <cstring>\n#include <string>\n')
        for c, v in ARRAYS:
            f.write("double %s[%d];\n" % (c, len(v)))
        f.write("static const struct { const char* name; double* p; std::size_t n; } chem_tables_list[] = {\n")
        for c, v in ARRAYS:
            f.write('    {"%s", %s, %d},\n' % (c, c, len(v)))
        f.write("};\nint chem_tables_data_load(const char* dir)\n{\n"
                '    const std::string p = std::string(dir) + "/sgchem_chem_tables.bin";\n'
                '    FILE* f = std::fopen(p.c_str(), "rb");\n'
                '    if (!f) { std::fprintf(stderr, "chem tables: cannot open %s\\n", p.c_str()); return 1; }\n'
                '    char magic[8]; uint64_t n = 0; bool bad = std::fread(magic, 1, 8, f) != 8 || std::memcmp(magic, "SGCT0001", 8) != 0 || std::fread(&n, 8, 1, f) != 1\n'
                '                    || n != sizeof(chem_tables_list) / sizeof(chem_tables_list[0]);\n'
                '    for (std::size_t i = 0; !bad && i < n; i++) {\n'
                '        char name[48]; uint64_t m = 0;\n'
                '        bad = std::fread(name, 1, 48, f) != 48 || std::fread(&m, 8, 1, f) != 1 || std::strncmp(name, chem_tables_list[i].name, 48) != 0\n'
                '              || m != chem_tables_list[i].n || std::fread(chem_tables_list[i].p, 8, m, f) != m;\n'
                '    }\n    bad = bad || std::fgetc(f) != EOF;\n    std::fclose(f);\n'
                '    if (bad) std::fprintf(stderr, "chem tables: %s does not match these sources\\n", p.c_str());\n'
                '    return bad ? 1 : 0;\n}\n')

def write_bin(path):
    with open(path, "wb") as f:
        f.write(b"SGCT0001" + struct.pack("<Q", len(ARRAYS)))
        for cname, vals in ARRAYS:
            f.write(cname.encode().ljust(48, b"\0") + struct.pack("<Q", len(vals)))
            f.write(struct.pack("<%dd" % len(vals), *vals))

def main(out_bin, out_header, loader=None):
    global CANON
    mol = strip_source(os.path.join(CANON, "mol_data.h"))
    coo = strip_source(os.path.join(CANON, "coolinmo.F"))
    isrf = strip_source(os.path.join(CANON, "isrf.h"))
    shd  = strip_source(os.path.join(CANON, "shield_data.h"))
    vis  = strip_source(os.path.join(CANON, "shield_data_visser.h"))
    hng  = strip_source(os.path.join(CANON, "highn_gamma.h"))
    h2h  = strip_source(os.path.join(CANON, "h2heat.h"))

    f = None
    if True:
        emit(f, "dat_h2_lte",     extract_data(mol, "h2_lte"),     41)
        emit(f, "dat_h2_h_rate",  extract_data(mol, "h2_h_rate"),  41)
        emit(f, "dat_h2_h2_rate", extract_data(mol, "h2_h2_rate"), 41)
        emit(f, "dat_co_temp",    extract_data(mol, "co_temp"),    12)
        emit(f, "dat_co_column",  extract_data(mol, "co_column"),  10)
        emit(f, "dat_co_data_L0", extract_data(mol, "co_data_L0"), 12)
        emit(f, "dat_co_data_LTE", extract_data(mol, "co_data_LTE"), 120)
        emit(f, "dat_co_data_n05", extract_data(mol, "co_data_n05"), 120)
        emit(f, "dat_co_data_alp", extract_data(mol, "co_data_alp"), 120)
        emit(f, "dat_co_vib_temp",   extract_data(mol, "co_vib_temp"),   6)
        emit(f, "dat_co_vib_column", extract_data(mol, "co_vib_column"), 8)
        emit(f, "dat_co_vib_LTE",    extract_data(mol, "co_vib_LTE"),   48)
        # ---- Gate 3: H2O rotational/vibrational raw data (cool_util tables) ----
        emit(f, "dat_h2o_temp_low",  extract_data(mol, "h2o_temp_low"),  6)
        emit(f, "dat_h2o_temp_high", extract_data(mol, "h2o_temp_high"), 5)
        emit(f, "dat_h2o_column",    extract_data(mol, "h2o_column"),   10)
        emit(f, "dat_h2o_L0_low_ortho", extract_data(mol, "h2o_L0_low_ortho"), 6)
        emit(f, "dat_h2o_L0_low_para",  extract_data(mol, "h2o_L0_low_para"),  6)
        emit(f, "dat_h2o_L0_high",      extract_data(mol, "h2o_L0_high"),      5)
        for q in ("LTE", "n05", "alp"):
            emit(f, "dat_h2o_%s_low_ortho" % q,
                 extract_data(mol, "h2o_%s_low_ortho" % q), 60)
            emit(f, "dat_h2o_%s_low_para" % q,
                 extract_data(mol, "h2o_%s_low_para" % q), 60)
            emit(f, "dat_h2o_%s_high" % q,
                 extract_data(mol, "h2o_%s_high" % q), 50)
        emit(f, "dat_h2o_vib_temp",   extract_data(mol, "h2o_vib_temp"),   6)
        emit(f, "dat_h2o_vib_column", extract_data(mol, "h2o_vib_column"), 8)
        emit(f, "dat_h2o_vib_LTE",    extract_data(mol, "h2o_vib_LTE"),   48)
        emit(f, "dat_coolatom", extract_data(coo, "coolatom"), 81)
        emit(f, "dat_ca2",      extract_data(coo, "ca2"),      76)
        emit(f, "dat_HeI_tbl",  extract_ctor(coo, "HeI_tbl"),  51)
        emit(f, "dat_HeII_tbl", extract_ctor(coo, "HeII_tbl"), 51)
        # ---- Gate 3: ISRF attenuation curves (calc_photo chi()) ----
        emit(f, "dat_chi_tab_mathis", extract_data(isrf, "chi_tab_mathis"), 200)
        emit(f, "dat_chi_tab_black",  extract_data(isrf, "chi_tab_black"),  200)
        # ---- Gate 3: CO / H2 shielding curves (cheminmo residual loops) ----
        emit(f, "dat_CO_shield_columns", extract_data(shd, "CO_shield_columns"), 51)
        emit(f, "dat_CO_shield_factors", extract_data(shd, "CO_shield_factors"), 51)
        emit(f, "dat_H2_shield_columns", extract_data(shd, "H2_shield_columns"), 43)
        emit(f, "dat_H2_shield_factors", extract_data(shd, "H2_shield_factors"), 43)
        # ---- Visser et al (2009) CO shielding grid (calc_photo co_shielding_visser) ----
        emit(f, "dat_vis_co_columns", extract_data(vis, "vis_co_columns"), 47)
        emit(f, "dat_vis_h2_columns", extract_data(vis, "vis_h2_columns"), 42)
        emit(f, "dat_vis_co_factors", extract_data(vis, "vis_co_factors"), 1974)
        # ---- Gate 3: high-n gamma table (compute_gamma.F) ----
        emit(f, "dat_hng", extract_data(hng, "hng"), 125)
        # ---- net 15: H2 formation-heating fraction (cool_util.F) ----
        emit(f, "dat_h2_rv_heat", extract_data(h2h, "h2_rv_heat"), 1914)
    write_bin(out_bin)
    if out_header:
        write_header(out_header)
    if loader:
        write_loader(loader)
    print("wrote", out_bin, os.path.getsize(out_bin), "bytes,", len(ARRAYS), "arrays")

if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("out"); ap.add_argument("--header"); ap.add_argument("--src"); ap.add_argument("--loader", help="DIR: write the extern header + loader .cc proposed for GIZMO")
    a = ap.parse_args()
    if a.src:
        CANON = a.src
    main(a.out, a.header, a.loader)
