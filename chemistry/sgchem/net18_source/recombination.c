double alpha_RR(double T, double RR_rates[]){
    // #HK NOTE: in many cases C and T2 are 0 so B = B

    // Unpact the values
    double A  = RR_rates[0];
    double B  = RR_rates[1];
    double T0 = RR_rates[2];
    double T1 = RR_rates[3];
    double C  = RR_rates[4];
    double T2 = RR_rates[5];

    B = B + (C * exp(-T2/T));

    double a0 = sqrt(T / T0);
    double a1 = pow((1. + sqrt(T / T0)),(1. - B));
    double a2 = pow((1. + sqrt(T / T1)),(1. + B));

    return A/(a0 * a1 * a2);
}

double alpha_DR(double T, double DR_rates_e[], double DR_rates_c[]){
    // # ! Dielectronic recombination
    // # ! T**(-3/2) * sum c_i * exp(-E_i/T)
    double comp_Alpha = 0.0;
    for (int i = 0; i < 9; i++) { 
        if (DR_rates_e[i] > 0.0){
            comp_Alpha += ( pow(T,-3./2.) * DR_rates_c[i] * exp(-1. * DR_rates_e[i] / T) );
        }
    }
    return comp_Alpha;
}

