// Loading in the radiative recombination rate data
void init_cloudy_rad_rec_data() {
    FILE *file;
    int i;
    int j;
    double help[9];

    printf("loading rec data\n");
	file = fopen("./data/rad_rec.dat", "r");
	if (file == NULL) {
		printf("Error: Could not open rad_rec.dat\n");
		exit(1);
	}

	fscanf( file, "%d", &i );

	while( true ) {
		fscanf( file, "%d %d", &i, &j );
		if( i == -1 && j == -1 )
			break;
		fscanf( file, "%le %le", &help[0], &help[1] );
		for( int l=0; l < 2; ++l )
			rrec[i][j][l] = (double)help[l];
	}
	while( true ) {
		fscanf( file, "%d %d", &i, &j );
		if( i == -1 && j == -1 )
			break;
		fscanf( file, "%le %le %le %le", &help[0], &help[1], &help[2], &help[3] );
		for( int l=0; l < 4; ++l )
			rnew[i][j][l] = (double)help[l];
	}
	while( true ) {
		fscanf( file, "%d", &i );
		if( i == -1 )
			break;
		fscanf( file, "%le %le %le", &help[0], &help[1], &help[2] );
		for( int l=0; l < 3; ++l )
			fe[i][l] = (double)help[l];
	}

	fclose( file );
}

double cloudy_rad_rec(int iz, int in, double t) {
	/*
     *** HK NOTE: this function was taken from CLOUDY

	 *** Input parameters:  iz - atomic number 
	 ***                    in - number of electrons from 1 to iz 
	 ***                    t  - temperature, K
	 *** return result:  - rate coefficient, cm^3 s^(-1)

	 */
	double tt;
	double rate;

	if( iz < 1 || iz > 30 ) {
		printf(" rad_rec called with insane atomic number, =%d\n", iz );
	}
	if( in < 1 || in > iz ) {
		printf(" rad_rec called with insane number elec =%d\n", in );
	}
	if( (((in <= 3 || in == 11) || (iz > 5 && iz < 9)) || iz == 10) || 
	  (iz == 26 && in > 11) ) {
		tt = sqrt(t/rnew[in-1][iz-1][2]);
		rate = 
		  rnew[in-1][iz-1][0]/(tt*pow(tt + 1.0,1.0 - rnew[in-1][iz-1][1])*
		  pow(1.0 + sqrt(t/rnew[in-1][iz-1][3]),1.0 + rnew[in-1][iz-1][1]));
	}
	else {
		tt = t*1.0e-04;
		if( iz == 26 && in <= 13 )
		{
			rate = fe[in-1][0]/pow(tt,fe[in-1][1] + 
			  fe[in-1][2]*log10(tt));
		}
		else
		{
			rate = rrec[in-1][iz-1][0]/pow(tt,(double)rrec[in-1][iz-1][1]);
		}
	}

	return rate;
}